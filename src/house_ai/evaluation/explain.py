def summary_metric(report: EvaluationReport, name: str) -> MetricClaim | None:
    return next(
        (m for m in report.metrics if m.metric == name and not m.subject_ids), None
    ) or next((m for m in report.metrics if m.metric == name), None)


def _fmt(m: MetricClaim | None, unit: str = "") -> str:
    if m is None:
        return "—"
    if m.value is None:
        return "not checked"
    v = m.value
    text = f"{v:.2f}" if isinstance(v, float) else str(v).lower() if isinstance(v, bool) else str(v)
    tag = "" if m.status.value == "measured" else f" ({m.status.value})"
    return f"{text}{(' ' + unit) if unit else ''}{tag}"


def explanation_markdown(
    plan: PlanVersion,
    version: int | None,
    report: EvaluationReport,
    program: SpaceProgram | None,
    *,
    banner: str | None = None,
) -> str:
    model = plan.model
    ver = f" v{version}" if version else ""
    lines = [f"# {plan.option_id}{ver}: {plan.label}", ""]
    if banner:
        lines += [f"> **{banner}**", ""]
    lines += [
        "> Design exploration "
        + (
            "produced by a constraint solver from the program. "
            if plan.generation
            else "drawn by hand. "
        )
        + "Nobody qualified has reviewed it; it has no permit, code or engineering status. "
        f"Compliance: {report.compliance.label}.",
        "",
        "## Strategy",
        "",
        STRATEGY_TEXT.get(plan.strategy or "", plan.strategy or "unknown"),
        "",
    ]
    if plan.change_request is not None:
        lines += ["## Requested change", "", f"> {plan.change_request.text}", ""]
        if plan.generation and plan.generation.revision_ops:
            lines += [
                "Applied as: " + ", ".join(f"`{o}`" for o in plan.generation.revision_ops),
                "",
            ]
    lines += ["## Levels", ""]
    for lv in sorted(model.levels, key=lambda lv: -lv.elevation_m):
        rooms = [
            s.name
            for s in model.spaces
            if s.level_id == lv.id and s.function.value not in ("corridor",)
        ]
        lines.append(f"- **{lv.name}** (FFL {lv.elevation_m:+.2f} m local): " + ", ".join(rooms))
    lines += [
        "",
        "## Rooms",
        "",
        "| Room | Level | Area m² | Program target m² | Program min m² |",
        "|---|---|---:|---:|---:|",
    ]
    items = {i.id: i for i in program.items} if program else {}
    for s in model.spaces:
        it = items.get(s.program_item_id or "")
        tgt = f"{it.target_area_m2:.1f}" if it and it.target_area_m2 else "—"
        mn = f"{it.min_area_m2:.1f}" if it and it.min_area_m2 else "—"
        lines.append(f"| {s.name} | {s.level_id} | {s.area_m2:.1f} | {tgt} | {mn} |")
    lines += [
        "",
        "## Measured results and trade-offs",
        "",
        "Status in brackets when a value is not measured exactly.",
        "",
    ]
    for name, label, unit in KEY_METRICS:
        m = summary_metric(report, name)
        if m is not None:
            lines.append(f"- {label}: {_fmt(m, unit)}")
    hard = report.hard_violations
    soft = [v for v in report.violations if v not in hard]
    lines += ["", f"## Violations ({len(hard)} hard, {len(soft)} soft)", ""]
    if not report.violations:
        lines.append("None found by the evaluators that ran.")
    for v in [*hard, *soft]:
        lines.append(f"- **{v.strength.value}** `{v.code}`: {v.message}")
    not_run = [e.name for e in report.evaluators if e.status.value != "ran"]
    if not_run:
        lines += ["", "Not evaluated (no evaluator yet): " + ", ".join(not_run) + "."]
    lines += ["", "## Assumptions", ""]
    for a in model.assumptions:
        lines.append(f"- [{a.status.value}] {a.statement}")
    if model.issues:
        lines += ["", "## Open issues", ""]
        for i in model.issues:
            lines.append(f"- [{i.severity.value}] {i.title}")
    if plan.generation is not None:
        g = plan.generation
        params = ", ".join(f"{k}={v}" for k, v in sorted(g.parameters.items()))
        lines += [
            "",
            "## How it was produced",
            "",
            f"- Generator `{g.generator}` {g.generator_version}, solver {g.solver} "
            f"{g.solver_version}: {g.solver_status}, objective {g.objective:.0f}, seed "
            f"{g.seed}, deterministic-time budget {g.deterministic_time_limit:g}.",
            f"- Parameters: {params}.",
        ]
    if plan.provenance.inputs:
        lines.append(
            "- Inputs: "
            + ", ".join(
                f"{r.kind.value}/{r.id} v{r.version} ({r.sha256[:12]})"
                for r in plan.provenance.inputs
            )
        )
    return "\n".join(lines) + "\n"


def footprint_iou(a: HouseModel, b: HouseModel) -> float:
    fa = unary_union([s.boundary.to_shapely() for s in a.spaces])
    fb = unary_union([s.boundary.to_shapely() for s in b.spaces])
    union = fa.union(fb).area
    return fa.intersection(fb).area / union if union else 1.0


def zoning_difference(a: HouseModel, b: HouseModel) -> float:
    """Share of program rooms whose level (relative to the entry) differs between two plans."""

    def rel(model: HouseModel) -> dict[str, float]:
        entry = next((lv.elevation_m for lv in model.levels if lv.id == "lv-entry"), 0.0)
        return {
            s.program_item_id: round(model.level(s.level_id).elevation_m - entry, 2)
            for s in model.spaces
            if s.program_item_id
        }

    ra, rb = rel(a), rel(b)
    common = set(ra) & set(rb)
    return sum(ra[k] != rb[k] for k in common) / len(common) if common else 0.0


def concept_signature(model: HouseModel) -> tuple[int, int]:
    """(floor levels, stairs): a coarse topology fingerprint."""
    return (len(model.levels), len(model.stairs))


def comparison_markdown(
    rows: list[tuple[PlanVersion, int | None, EvaluationReport]],
    infeasible: list[tuple[str, str]],
    *,
    banner: str | None = None,
) -> str:
    lines = ["# Plan concepts compared", ""]
    if banner:
        lines += [f"> **{banner}**", ""]
    lines += [
        "Each column is one concept; values are individual metrics, not a combined score. "
        "Status in brackets when not measured exactly.",
        "",
    ]
    head = (
        "| Metric | "
        + " | ".join(f"{p.option_id} v{v}" if v else p.option_id for p, v, _ in rows)
        + " |"
    )
    lines += [head, "|---|" + "---|" * len(rows)]
    lines.append("| Strategy | " + " | ".join(p.strategy or "" for p, _, _ in rows) + " |")
    lines.append(
        "| Hard violations | " + " | ".join(str(len(r.hard_violations)) for _, _, r in rows) + " |"
    )
    lines.append(
        "| Soft violations | "
        + " | ".join(str(len(r.violations) - len(r.hard_violations)) for _, _, r in rows)
        + " |"
    )
    for name, label, unit in KEY_METRICS:
        cells = [_fmt(summary_metric(r, name), unit) for _, _, r in rows]
        if any(c != "—" for c in cells):
            lines.append(f"| {label} | " + " | ".join(cells) + " |")
    if len(rows) > 1:
        lines += [
            "",
            "## How different the concepts are (measured)",
            "",
            "| Pair | Footprint overlap (IoU) | Rooms on a different level | Levels/stairs |",
            "|---|---:|---:|---|",
        ]
        for i, (pa, _, _) in enumerate(rows):
            for pb, _, _ in rows[i + 1 :]:
                iou = footprint_iou(pa.model, pb.model)
                zd = zoning_difference(pa.model, pb.model)
                sa, sb = concept_signature(pa.model), concept_signature(pb.model)
                lines.append(
                    f"| {pa.option_id} / {pb.option_id} | {iou:.2f} | {zd:.0%} | "
                    f"{sa[0]}/{sa[1]} vs {sb[0]}/{sb[1]} |"
                )
    if infeasible:
        lines += ["", "## Strategies that could not be laid out", ""]
        for strategy, reason in infeasible:
            lines.append(f"- **{strategy}**: {reason}")
    lines += [
        "",
        "These are design explorations. None is reviewed, engineered or checked "
        "against a building code; see docs/PROFESSIONAL_HANDOFF.md.",
        "",
    ]
    return "\n".join(lines)


def revision_report(
    *,
    report_id: str,
    text: str,
    before: PlanVersion,
    after: PlanVersion,
    before_ref: ArtifactRef,
    after_ref: ArtifactRef,
    before_eval: EvaluationReport | None,
    after_eval: EvaluationReport,
    provenance: Provenance,
) -> RevisionReport:
    a = {s.id: s for s in before.model.spaces}
    b = {s.id: s for s in after.model.spaces}
    changed = sorted(
        k
        for k in set(a) & set(b)
        if a[k].level_id != b[k].level_id
        or a[k].boundary.model_dump() != b[k].boundary.model_dump()
    )
    st_a = {s.id: s.model_dump() for s in before.model.stairs}
    st_b = {s.id: s.model_dump() for s in after.model.stairs}
    stairs = sorted(k for k in set(st_a) | set(st_b) if st_a.get(k) != st_b.get(k))
    areas = [
        AreaChange(
            space_id=k,
            before_m2=round(a[k].area_m2, 3) if k in a else None,
            after_m2=round(b[k].area_m2, 3) if k in b else None,
        )
        for k in sorted(set(changed) | (set(a) ^ set(b)))
    ]
    metric_changes: list[MetricChange] = []
    if before_eval is not None:
        old = {m.metric: m.value for m in before_eval.metrics if not m.subject_ids}
        new = {m.metric: m.value for m in after_eval.metrics if not m.subject_ids}
        for k in sorted(set(old) | set(new)):
            if old.get(k) != new.get(k):
                metric_changes.append(MetricChange(metric=k, before=old.get(k), after=new.get(k)))

    def keys(r: EvaluationReport | None) -> set[str]:
        return (
            {f"{v.strength.value}:{v.code}:{','.join(v.subject_ids)}" for v in r.violations}
            if r
            else set()
        )

    old_v, new_v = keys(before_eval), keys(after_eval)
    old_asm = {x.statement for x in before.model.assumptions}
    return RevisionReport(
        id=report_id,
        requested_change=text,
        from_version=before_ref,
        to_version=after_ref,
        geometry_changed=changed + stairs,
        rooms_added=sorted(set(b) - set(a)),
        rooms_removed=sorted(set(a) - set(b)),
        rooms_changed=changed,
        area_changes=areas,
        metric_changes=metric_changes,
        new_violations=sorted(new_v - old_v),
        resolved_violations=sorted(old_v - new_v),
        assumptions=[x.statement for x in after.model.assumptions if x.statement not in old_asm]
        + [
            f"revision operation: {op}"
            for op in (after.generation.revision_ops if after.generation else [])
        ],
        provenance=provenance,
    )


def revision_markdown(r: RevisionReport) -> str:
    lines = [
        f"# Revision {r.id}",
        "",
        f"> {r.requested_change}",
        "",
        f"From {r.from_version.id} v{r.from_version.version} to "
        f"{r.to_version.id} v{r.to_version.version}.",
        "",
    ]
    for title, items in (
        ("Rooms added", r.rooms_added),
        ("Rooms removed", r.rooms_removed),
        ("Rooms changed", r.rooms_changed),
        ("New violations", r.new_violations),
        ("Resolved violations", r.resolved_violations),
        ("Assumptions", r.assumptions),
    ):
        lines += [f"## {title}", ""] + ([f"- {i}" for i in items] or ["- none"]) + [""]
    lines += ["## Area changes", "", "| Space | Before m² | After m² |", "|---|---:|---:|"]
    for c in r.area_changes:
        lines.append(
            f"| {c.space_id} | {c.before_m2 if c.before_m2 is not None else '—'} | "
            f"{c.after_m2 if c.after_m2 is not None else '—'} |"
        )
    lines += ["", "## Metric changes", "", "| Metric | Before | After |", "|---|---|---|"]
    for m in r.metric_changes:
        lines.append(f"| {m.metric} | {m.before} | {m.after} |")
    return "\n".join(lines) + "\n"
