"""Generate TypeScript types from schemas/*.schema.json for apps/reviewer."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
SCHEMAS_DIR = REPO_ROOT / "schemas"
TARGET_FILE = REPO_ROOT / "apps" / "reviewer" / "src" / "types" / "schemas.ts"


def _ref_to_name(ref: str) -> str:
    """Extract type name from a #/$defs/Name ref."""
    return ref.split("/")[-1]


def _ts_type(prop: dict[str, Any], defs: dict[str, Any]) -> str:  # noqa: C901
    """Map a JSON schema property definition to a TypeScript type string."""
    if "$ref" in prop:
        return _ref_to_name(prop["$ref"])

    if "enum" in prop:
        return " | ".join(json.dumps(val) for val in prop["enum"])

    if "anyOf" in prop:
        types = [_ts_type(sub, defs) for sub in prop["anyOf"]]
        # deduplicate while preserving order
        unique_types = list(dict.fromkeys(types))
        return " | ".join(unique_types)

    if "oneOf" in prop:
        types = [_ts_type(sub, defs) for sub in prop["oneOf"]]
        unique_types = list(dict.fromkeys(types))
        return " | ".join(unique_types)

    schema_type = prop.get("type")

    if schema_type == "string":
        return "string"
    if schema_type in ("number", "integer"):
        return "number"
    if schema_type == "boolean":
        return "boolean"
    if schema_type == "null":
        return "null"

    if schema_type == "array":
        items = prop.get("items")
        if items:
            item_type = _ts_type(items, defs)
            if " | " in item_type:
                return f"({item_type})[]"
            return f"{item_type}[]"
        return "any[]"

    if schema_type == "object":
        add_props = prop.get("additionalProperties")
        if isinstance(add_props, dict):
            return f"Record<string, {_ts_type(add_props, defs)}>"
        if "properties" in prop:
            sub_props = []
            req = set(prop.get("required", []))
            for k, v in prop["properties"].items():
                opt = "" if k in req else "?"
                sub_props.append(f"{k}{opt}: {_ts_type(v, defs)};")
            return "{ " + " ".join(sub_props) + " }"
        return "Record<string, any>"

    return "any"


def generate_typescript_content() -> str:  # noqa: C901
    """Parse all JSON schemas and render complete TypeScript source code."""
    all_defs: dict[str, dict[str, Any]] = {}
    root_schemas: dict[str, dict[str, Any]] = {}

    for schema_file in sorted(SCHEMAS_DIR.glob("*.schema.json")):
        data = json.loads(schema_file.read_text(encoding="utf-8"))
        for def_name, def_schema in data.get("$defs", {}).items():
            if def_name not in all_defs:
                all_defs[def_name] = def_schema
        title = data.get("title") or schema_file.stem.removesuffix(".schema")
        root_schemas[title] = data

    lines: list[str] = [
        "/**",
        " * Auto-generated TypeScript types from schemas/*.schema.json.",
        " * Generated by tools/generate_reviewer_types.py. DO NOT EDIT BY HAND.",
        " */",
        "",
    ]

    # 1. Output definitions ($defs)
    for name in sorted(all_defs.keys()):
        schema = all_defs[name]
        desc = schema.get("description")
        if desc:
            lines.append(f"/** {desc} */")

        if "enum" in schema:
            variants = " | ".join(json.dumps(val) for val in schema["enum"])
            lines.append(f"export type {name} = {variants};")
            lines.append("")
        elif schema.get("type") == "object" or "properties" in schema:
            lines.append(f"export interface {name} {{")
            required = set(schema.get("required", []))
            props = schema.get("properties", {})
            for prop_name, prop_def in sorted(props.items()):
                prop_desc = prop_def.get("description")
                if prop_desc:
                    lines.append(f"  /** {prop_desc} */")
                opt = "" if prop_name in required else "?"
                ts_t = _ts_type(prop_def, all_defs)
                lines.append(f"  {prop_name}{opt}: {ts_t};")
            lines.append("}")
            lines.append("")
        else:
            ts_t = _ts_type(schema, all_defs)
            lines.append(f"export type {name} = {ts_t};")
            lines.append("")

    # 2. Output root schemas (if not already output in $defs)
    for title in sorted(root_schemas.keys()):
        if title in all_defs:
            continue
        schema = root_schemas[title]
        desc = schema.get("description")
        if desc:
            lines.append(f"/** {desc} */")

        if "enum" in schema:
            variants = " | ".join(json.dumps(val) for val in schema["enum"])
            lines.append(f"export type {title} = {variants};")
            lines.append("")
        elif schema.get("type") == "object" or "properties" in schema:
            lines.append(f"export interface {title} {{")
            required = set(schema.get("required", []))
            props = schema.get("properties", {})
            for prop_name, prop_def in sorted(props.items()):
                prop_desc = prop_def.get("description")
                if prop_desc:
                    lines.append(f"  /** {prop_desc} */")
                opt = "" if prop_name in required else "?"
                ts_t = _ts_type(prop_def, all_defs)
                lines.append(f"  {prop_name}{opt}: {ts_t};")
            lines.append("}")
            lines.append("")

    # 3. Output ReviewerBundle and related UI interfaces
    lines.extend(
        [
            "/** Gate approval command and status */",
            "export interface GateApprovalInfo {",
            "  name: string;",
            "  approved: boolean;",
            "  approved_at?: string | null;",
            "  approved_by?: string | null;",
            "  artifact?: ArtifactRef | null;",
            "  approve_command: string;",
            "  confirm_command?: string;",
            "  description: string;",
            "}",
            "",
            "/** One plan option entry inside the reviewer bundle */",
            "export interface ReviewerPlanEntry {",
            "  option_id: string;",
            "  label: string;",
            "  strategy?: string | null;",
            "  version?: number | null;",
            "  is_exploratory: boolean;",
            "  exploratory_warning?: string;",
            "  plan: PlanVersion;",
            "  plan_ref?: ArtifactRef;",
            "  evaluation?: EvaluationReport | null;",
            "  revision?: RevisionReport | null;",
            "  svg?: string | null;",
            "}",
            "",
            "/** Top-level bundle JSON structure exported by house-ai reviewer export */",
            "export interface ReviewerBundle {",
            "  schema_version: string;",
            "  project: {",
            "    name: string;",
            "    state: string;",
            "    manifest?: ProjectManifest | null;",
            "  };",
            "  gates: Record<string, GateApprovalInfo>;",
            "  site?: Site | null;",
            "  program?: SpaceProgram | null;",
            "  brief?: DesignBrief | null;",
            "  plans: ReviewerPlanEntry[];",
            "  comparison_markdown?: string;",
            "}",
            "",
        ]
    )

    return "\n".join(lines)


def main_cli() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check for drift without writing")
    args = parser.parse_args()

    generated_content = generate_typescript_content()

    if args.check:
        if not TARGET_FILE.exists():
            print(f"MISSING: {TARGET_FILE}", file=sys.stderr)
            return 1
        current_content = TARGET_FILE.read_text(encoding="utf-8")
        if current_content != generated_content:
            print(f"DRIFT: {TARGET_FILE} differs from generated schemas", file=sys.stderr)
            return 1
        print("OK: TypeScript schema types are up to date")
        return 0

    TARGET_FILE.parent.mkdir(parents=True, exist_ok=True)
    TARGET_FILE.write_text(generated_content, encoding="utf-8")
    print(f"wrote {TARGET_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main_cli())
